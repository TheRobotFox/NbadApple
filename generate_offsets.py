from pathlib import Path

ROOT = Path(__file__).resolve().parent


def generate():
    data = (ROOT / "frames.tns").read_bytes()
    offsets = [0]
    pixels = 0
    for position, run in enumerate(data, 1):
        pixels += run
        if pixels > 320 * 240:
            raise ValueError(f"Invalid run at byte {position}")
        if pixels == 320 * 240:
            offsets.append(position)
            pixels = 0
    if pixels or offsets[-1] != len(data) or len(offsets) < 2:
        raise ValueError("Incomplete or empty frame data")
    longest = max(b - a for a, b in zip(offsets, offsets[1:]))
    rows = [", ".join(map(str, offsets[i:i + 8]))
            for i in range(0, len(offsets), 8)]
    header = (
        "/* Generated by generate_offsets.py from frames.tns. */\n"
        "#ifndef FRAME_OFFSETS_H\n#define FRAME_OFFSETS_H\n"
        f"#define FRAMES {len(offsets) - 1}\n"
        f"#define ENCODEDBUFFERCHACHE {longest}\n"
        "static const unsigned int frame_offsets[FRAMES + 1] = {\n    "
        + ",\n    ".join(rows) + "\n};\n#endif\n"
    )
    (ROOT / "Player/frame_offsets.h").write_text(header)
    print(f"Indexed {len(offsets) - 1} frames; largest: {longest} bytes")


if __name__ == "__main__":
    generate()
